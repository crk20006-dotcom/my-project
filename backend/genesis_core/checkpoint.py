"""
Checkpoint Saving, Loading & Metadata Inspection for Genesis Core.

Stores standard PyTorch `.pt` checkpoints alongside pure-JSON sidecar `.meta.json`
files so lightweight diagnostics (and Node.js status probes) can inspect step counts,
losses, architecture parameters, and experimental status without loading tensors into RAM.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from genesis_core.config import GenesisCoreConfig, TrainingConfig
from genesis_core.model import GenesisCoreTransformer, HAS_TORCH

if HAS_TORCH:
    import torch


def sidecar_meta_path(checkpoint_path: str | Path) -> Path:
    ckpt = Path(checkpoint_path)
    return ckpt.with_suffix(".meta.json")


def save_checkpoint(
    checkpoint_path: str | Path,
    model: Any,
    optimizer: Any,
    model_config: GenesisCoreConfig,
    train_config: TrainingConfig,
    step: int,
    train_loss: float | None,
    val_loss: float | None,
    tokenizer_path: str | Path | None = None,
    extra_meta: dict[str, Any] | None = None,
) -> Path:
    """Save model/optimizer checkpoint (.pt) and pure-JSON companion sidecar metadata."""
    if not HAS_TORCH:
        raise RuntimeError("PyTorch is required to save model checkpoints.")

    ckpt_path = Path(checkpoint_path)
    ckpt_path.parent.mkdir(parents=True, exist_ok=True)
    created_at = datetime.now(timezone.utc).isoformat()

    metadata: dict[str, Any] = {
        "format": "genesis_core_checkpoint_v1",
        "experimental": True,
        "trained": step > 0,
        "model_status": "experimental_trained" if step > 0 else "untrained_experimental",
        "trained_steps": int(step),
        "train_loss": round(float(train_loss), 6) if train_loss is not None else None,
        "val_loss": round(float(val_loss), 6) if val_loss is not None else None,
        "parameter_count": model.count_parameters(),
        "model_config": model_config.to_dict(),
        "train_config": train_config.to_dict(),
        "tokenizer_path": str(tokenizer_path) if tokenizer_path else None,
        "checkpoint_file": str(ckpt_path.name),
        "created_at": created_at,
    }
    if extra_meta:
        metadata.update(extra_meta)

    payload = {
        "format": "genesis_core_checkpoint_v1",
        "experimental": True,
        "step": int(step),
        "train_loss": train_loss,
        "val_loss": val_loss,
        "model_config": model_config.to_dict(),
        "train_config": train_config.to_dict(),
        "tokenizer_path": str(tokenizer_path) if tokenizer_path else None,
        "created_at": created_at,
        "model_state_dict": model.state_dict(),
        "optimizer_state_dict": optimizer.state_dict() if optimizer is not None else None,
        "extra_meta": extra_meta or {},
    }
    torch.save(payload, ckpt_path)
    sidecar_meta_path(ckpt_path).write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    return ckpt_path


def load_checkpoint(
    checkpoint_path: str | Path,
    device: str = "cpu",
    load_optimizer: bool = False,
) -> dict[str, Any]:
    """Load a locally trained Genesis Core `.pt` checkpoint and instantiate its Transformer."""
    if not HAS_TORCH:
        raise RuntimeError("PyTorch is required to load Genesis Core `.pt` checkpoints.")

    ckpt_path = Path(checkpoint_path)
    if not ckpt_path.exists():
        raise FileNotFoundError(f"Checkpoint file does not exist: {ckpt_path}")

    # Only read trusted local checkpoints generated by Genesis Core
    payload = torch.load(ckpt_path, map_location=device, weights_only=False)
    if not isinstance(payload, dict) or payload.get("format") != "genesis_core_checkpoint_v1":
        raise ValueError(f"Invalid Genesis Core checkpoint format in {ckpt_path}.")

    model_cfg = GenesisCoreConfig.from_dict(payload["model_config"])
    model = GenesisCoreTransformer(model_cfg)
    model.load_state_dict(payload["model_state_dict"])
    model.to(device)
    model.eval()

    result: dict[str, Any] = {
        "model": model,
        "model_config": model_cfg,
        "train_config": TrainingConfig.from_dict(payload.get("train_config") or {}),
        "step": int(payload.get("step", 0)),
        "train_loss": payload.get("train_loss"),
        "val_loss": payload.get("val_loss"),
        "tokenizer_path": payload.get("tokenizer_path"),
        "experimental": True,
        "created_at": payload.get("created_at"),
    }
    if load_optimizer:
        result["optimizer_state_dict"] = payload.get("optimizer_state_dict")
    return result


def inspect_checkpoint_metadata(checkpoint_path: str | Path) -> dict[str, Any]:
    """
    Pure-Python inspection of a checkpoint path and its `.meta.json` sidecar.
    Safe to run without PyTorch installed.
    """
    ckpt_path = Path(checkpoint_path)
    meta_path = sidecar_meta_path(ckpt_path)
    pt_exists = ckpt_path.exists() and ckpt_path.is_file()
    meta_exists = meta_path.exists() and meta_path.is_file()

    base: dict[str, Any] = {
        "checkpoint_path": str(ckpt_path),
        "meta_path": str(meta_path),
        "checkpoint_exists": pt_exists,
        "metadata_exists": meta_exists,
        "experimental": True,
        "trained": False,
        "model_status": "untrained_experimental",
        "trained_steps": 0,
        "train_loss": None,
        "val_loss": None,
        "torch_available": HAS_TORCH,
        "model_config": None,
        "tokenizer_path": None,
        "created_at": None,
    }

    if meta_exists:
        try:
            meta = json.loads(meta_path.read_text(encoding="utf-8"))
            if isinstance(meta, dict):
                steps = int(meta.get("trained_steps") or 0)
                base.update(
                    {
                        "trained": bool(pt_exists and steps > 0),
                        "model_status": (
                            "experimental_trained" if (pt_exists and steps > 0) else "untrained_experimental"
                        ),
                        "trained_steps": steps,
                        "train_loss": meta.get("train_loss"),
                        "val_loss": meta.get("val_loss"),
                        "parameter_count": meta.get("parameter_count"),
                        "model_config": meta.get("model_config"),
                        "tokenizer_path": meta.get("tokenizer_path"),
                        "created_at": meta.get("created_at"),
                    }
                )
        except Exception as exc:  # pragma: no cover
            base["metadata_error"] = str(exc)

    return base
